// Helper function: translate a value using the dictionary, fallback to English
function translateValue(value, langDict) {
  if (typeof value !== 'string') return value;
  
  // Check exact match first
  if (langDict[value]) return langDict[value];
  
  // For values with interpolation {{...}}, try matching the template
  // Check if value starts with any known translation key
  for (const [eng, trans] of Object.entries(langDict)) {
    if (value === eng) return trans;
  }
  
  // Return English as fallback
  return value;
}

// Generate translation file for a given language and namespace
function generateTranslation(lang, namespace) {
  const enFile = path.join(LOCALES_DIR, 'en', `${namespace}.json`);
  if (!fs.existsSync(enFile)) {
    console.warn(`English file not found: ${enFile}`);
    return;
  }
  
  const enData = JSON.parse(fs.readFileSync(enFile, 'utf8'));
  const langDict = translations[lang] || {};
  const result = {};
  
  for (const [key, value] of Object.entries(enData)) {
    result[key] = translateValue(value, langDict);
  }
  
  const outDir = path.join(LOCALES_DIR, lang);
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }
  
  const outFile = path.join(outDir, `${namespace}.json`);
  fs.writeFileSync(outFile, JSON.stringify(result, null, 2) + '\n', 'utf8');
  console.log(`✓ Created ${lang}/${namespace}.json`);
}

