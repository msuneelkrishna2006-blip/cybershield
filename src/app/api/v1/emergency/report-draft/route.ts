/**
 * CyberShield India — Emergency Report Draft API
 * POST /api/v1/emergency/report-draft
 *
 * Generates a pre-filled complaint draft from scan details,
 * suitable for reading to a helpline operator or pasting
 * into cybercrime.gov.in.
 */

import { NextRequest } from 'next/server';
import { z } from 'zod';
import { prisma } from '@/lib/prisma';
import { verifyAccessToken } from '@/lib/auth/jwt';
import { getAccessToken } from '@/lib/auth/cookies';
import { apiSuccess, apiError } from '@/lib/api/response';

const reportDraftSchema = z.object({
  scanId: z.string().min(1),
});

export async function POST(request: NextRequest) {
  try {
    const token = getAccessToken(request);
    if (!token) return apiError('UNAUTHORIZED', 'Authentication required', 401);

    let payload;
    try {
      payload = await verifyAccessToken(token);
    } catch {
      return apiError('UNAUTHORIZED', 'Invalid or expired token', 401);
    }

    const body = await request.json();
    const parsed = reportDraftSchema.safeParse(body);

    if (!parsed.success) {
      return apiError('VALIDATION_ERROR', 'Invalid request', 400, parsed.error.flatten().fieldErrors);
    }

    const { scanId } = parsed.data;

    const scan = await prisma.scanRecord.findUnique({
      where: { id: scanId },
    });

    if (!scan) {
      return apiError('NOT_FOUND', 'Scan record not found', 404);
    }

    // Parse stored data
    let agentResults: any = {};
    let recommendations: string[] = [];
    try { agentResults = JSON.parse(scan.agentResults || '{}'); } catch { /* */ }
    try { recommendations = JSON.parse(scan.recommendations || '[]'); } catch { /* */ }

    const indicators = agentResults.indicators || [];
    const categoryLabel = scan.category.replace(/_/g, ' ');

    // Generate structured complaint draft
    const draft = [
      `CYBERCRIME COMPLAINT REPORT`,
      `Generated by CyberShield India Platform`,
      `Date: ${new Date().toLocaleDateString('en-IN', { day: '2-digit', month: 'long', year: 'numeric' })}`,
      `Time: ${new Date().toLocaleTimeString('en-IN')}`,
      ``,
      `--- INCIDENT DETAILS ---`,
      ``,
      `Incident Type: ${categoryLabel}`,
      `Risk Level: ${scan.riskLevel}`,
      `Risk Score: ${scan.riskScore}/100`,
      `Scan Type: ${scan.type.toUpperCase()}`,
      `Detected At: ${scan.createdAt.toLocaleDateString('en-IN')} ${scan.createdAt.toLocaleTimeString('en-IN')}`,
      ``,
      `--- WHAT WAS DETECTED ---`,
      ``,
      scan.summary || 'Content was analyzed and flagged as potentially dangerous.',
      ``,
      ...(indicators.length > 0 ? [
        `--- EVIDENCE / INDICATORS ---`,
        ``,
        ...indicators.map((ind: string, i: number) => `${i + 1}. ${ind}`),
        ``,
      ] : []),
      `--- SUSPICIOUS CONTENT (TRUNCATED) ---`,
      ``,
      scan.input.substring(0, 300) + (scan.input.length > 300 ? '...' : ''),
      ``,
      `--- RECOMMENDED ACTIONS ---`,
      ``,
      ...recommendations.map((rec: string, i: number) => `${i + 1}. ${rec}`),
      ``,
      `--- HELPLINE NUMBERS ---`,
      ``,
      `• National Cyber Crime Helpline: 1930`,
      `• Online Complaint Portal: cybercrime.gov.in`,
      `• Police Emergency: 112`,
      `• Women Safety: 181`,
      `• Child Helpline: 1098`,
      ``,
      `--- DISCLAIMER ---`,
      `This report was generated by CyberShield, an independent AI-powered`,
      `digital safety platform. This is not a legal document. Please file a`,
      `formal complaint at cybercrime.gov.in or your nearest police station.`,
    ].join('\n');

    return apiSuccess({
      draft,
      scanId: scan.id,
      riskLevel: scan.riskLevel,
      category: categoryLabel,
    });
  } catch (error) {
    console.error('[Report Draft] Error:', error instanceof Error ? error.message : 'Unknown');
    return apiError('INTERNAL_ERROR', 'Failed to generate report draft', 500);
  }
}
